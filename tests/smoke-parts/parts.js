// Runs in every part, in no list: an error raised by a part's checks fails that part.
const EVERY_PART = ['noConsoleErrors'];

// Every check name assigned in tests/smoke.js and in the group files beside this one.
function smokeCheckNames() {
  const files = [path.join(__dirname, '..', 'smoke.js'),
    ...fs.readdirSync(__dirname).filter(f => f.endsWith('.js') && f !== 'parts.js').sort().map(f => path.join(__dirname, f))];
  return [...new Set(files.flatMap(f => [...fs.readFileSync(f, 'utf8')
    .matchAll(/^\s*(?:if \(want\('[^']*'\)\) )?checks\.([A-Za-z0-9_$]+)\s*=(?!=)/gm)].map(m => m[1])))];
}

// What is wrong with the lists against these check names: [] or one sentence per problem.
function partProblems(names) {
  const problems = [];
  const where = {};
  for (const [p, list] of Object.entries(PARTS)) list.forEach(n => { (where[n] = where[n] || []).push(p); });
  for (const n of names) {
    if (EVERY_PART.includes(n)) {
      if (where[n]) problems.push(`${n} runs in every part, so it belongs in no list (listed in part ${where[n].join(', ')})`);
    } else if (!where[n]) problems.push(`${n} is in no part`);
    else if (where[n].length > 1) problems.push(`${n} is in parts ${where[n].join(' and ')}`);
  }
  Object.keys(where).filter(n => !names.includes(n))
    .forEach(n => problems.push(`${n} is listed in part ${where[n].join(', ')} but no such check exists`));
  return problems;
}

module.exports = { PARTS, EVERY_PART, smokeCheckNames, partProblems };
